package com.ses.whodatidols.model;

import java.sql.Timestamp;
import java.util.UUID;

public class StreamLive {
    private UUID id;
    private String title;
    private String description;
    private String contentType;     // "Movie" or "Episode"
    private UUID contentId;         // Movie ID or Episode ID
    private String contentName;     // Title of movie or "Series Name - S1E1"
    private String slug;            // Content slug
    private String posterUrl;       // /media/image/{id}
    private String videoUrl;        // /media/video/{contentId}/playlist.m3u8
    private Timestamp scheduledStartTime;
    private int durationMinutes;
    private int durationSeconds;
    private Timestamp endTime;
    private boolean active;
    private Timestamp createdAt;

    public StreamLive() {
    }

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getContentType() {
        return contentType;
    }

    public void setContentType(String contentType) {
        this.contentType = contentType;
    }

    public UUID getContentId() {
        return contentId;
    }

    public void setContentId(UUID contentId) {
        this.contentId = contentId;
    }

    public String getContentName() {
        return contentName;
    }

    public void setContentName(String contentName) {
        this.contentName = contentName;
    }

    public String getSlug() {
        return slug;
    }

    public void setSlug(String slug) {
        this.slug = slug;
    }

    public String getPosterUrl() {
        return posterUrl;
    }

    public void setPosterUrl(String posterUrl) {
        this.posterUrl = posterUrl;
    }

    public String getVideoUrl() {
        return videoUrl;
    }

    public void setVideoUrl(String videoUrl) {
        this.videoUrl = videoUrl;
    }

    public Timestamp getScheduledStartTime() {
        return scheduledStartTime;
    }

    public void setScheduledStartTime(Timestamp scheduledStartTime) {
        this.scheduledStartTime = scheduledStartTime;
    }

    public int getDurationMinutes() {
        return durationMinutes;
    }

    public void setDurationMinutes(int durationMinutes) {
        this.durationMinutes = durationMinutes;
    }

    public int getDurationSeconds() {
        return durationSeconds;
    }

    public void setDurationSeconds(int durationSeconds) {
        this.durationSeconds = durationSeconds;
    }

    public Timestamp getEndTime() {
        return endTime;
    }

    public void setEndTime(Timestamp endTime) {
        this.endTime = endTime;
    }

    public boolean isActive() {
        return active;
    }

    public void setActive(boolean active) {
        this.active = active;
    }

    public Timestamp getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Timestamp createdAt) {
        this.createdAt = createdAt;
    }
}
